#!/usr/bin/env bash
# ===========================================================================
# Day-zero bootstrap: create the Terraform remote-state backend.
#
# This is the one piece of infrastructure that CANNOT be created by Terraform,
# because Terraform needs it to exist before it can store state. Every real
# platform has exactly this chicken-and-egg script.
#
# What it creates:
#   * a resource group for shared platform state
#   * a storage account with versioning, soft delete, TLS 1.2, no public blobs
#   * a container for the state files
#   * RBAC so YOU and the CI identity can read/write blobs via Entra ID
#     (no storage account keys are used or needed)
#
# Run once per tenant:   ./scripts/bootstrap-tfstate.sh
# ===========================================================================
set -euo pipefail

LOCATION="${LOCATION:-centralindia}"
RG="${TFSTATE_RG:-rg-tfstate-shared}"
CONTAINER="${TFSTATE_CONTAINER:-tfstate}"

green() { printf '\033[32m%s\033[0m\n' "$1"; }
info()  { printf '\033[36m%s\033[0m\n' "$1"; }
die()   { printf '\033[31mERROR: %s\033[0m\n' "$1" >&2; exit 1; }

command -v az >/dev/null || die "Azure CLI not found. Install it first."
az account show >/dev/null 2>&1 || die "Not logged in. Run: az login"

SUB_ID=$(az account show --query id -o tsv)
SUB_NAME=$(az account show --query name -o tsv)
USER_OID=$(az ad signed-in-user show --query id -o tsv)

# Storage account names are globally unique, 3-24 chars, lowercase alphanumeric.
# Deriving from the subscription id makes this script idempotent: re-running it
# targets the same account instead of creating a second one.
SUFFIX=$(printf '%s' "$SUB_ID" | tr -d '-' | cut -c1-8)
SA="sttfstateerp${SUFFIX}"

info "=============================================================="
info "Subscription : ${SUB_NAME}"
info "              ${SUB_ID}"
info "Location     : ${LOCATION}"
info "Resource grp : ${RG}"
info "Storage acct : ${SA}"
info "Container    : ${CONTAINER}"
info "=============================================================="
read -r -p "Proceed? [y/N] " reply
[[ "$reply" =~ ^[Yy]$ ]] || { echo "Aborted."; exit 0; }

# ------------------------------------------------------------ resource group
info "Creating resource group..."
az group create \
  --name "$RG" \
  --location "$LOCATION" \
  --tags Workload=platform Environment=shared CostCentre=CC-PLATFORM-001 \
         Owner="$(az ad signed-in-user show --query userPrincipalName -o tsv)" \
         DataClass=confidential ManagedBy=bootstrap-script \
  --only-show-errors -o none

# ---------------------------------------------------------- storage account
info "Creating storage account (this takes ~30s)..."
az storage account create \
  --name "$SA" \
  --resource-group "$RG" \
  --location "$LOCATION" \
  --sku Standard_LRS \
  --kind StorageV2 \
  --access-tier Hot \
  --min-tls-version TLS1_2 \
  --https-only true \
  --allow-blob-public-access false \
  --allow-shared-key-access false \
  --default-action Allow \
  --only-show-errors -o none

# --allow-shared-key-access false is the important one: it makes account keys
# useless, so the ONLY way to reach state is Entra ID + RBAC. A leaked key is
# then not a path to your infrastructure state (which contains secrets).

info "Enabling blob versioning, change feed and soft delete..."
az storage account blob-service-properties update \
  --account-name "$SA" \
  --resource-group "$RG" \
  --enable-versioning true \
  --enable-change-feed true \
  --enable-delete-retention true \
  --delete-retention-days 30 \
  --enable-container-delete-retention true \
  --container-delete-retention-days 30 \
  --only-show-errors -o none

# ------------------------------------------------------------------- RBAC
info "Granting yourself Storage Blob Data Contributor..."
SA_ID=$(az storage account show -n "$SA" -g "$RG" --query id -o tsv)
az role assignment create \
  --assignee-object-id "$USER_OID" \
  --assignee-principal-type User \
  --role "Storage Blob Data Contributor" \
  --scope "$SA_ID" \
  --only-show-errors -o none 2>/dev/null || info "  (role already assigned)"

info "Waiting 30s for the role assignment to propagate..."
sleep 30

# -------------------------------------------------------------- container
info "Creating the state container..."
az storage container create \
  --name "$CONTAINER" \
  --account-name "$SA" \
  --auth-mode login \
  --only-show-errors -o none

# ----------------------------------------------- write the backend configs
for env in dev test prod; do
  dir="infra/terraform/envs/${env}"
  [ -d "$dir" ] || continue
  cat > "${dir}/backend.hcl" <<EOF
# Generated by scripts/bootstrap-tfstate.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
resource_group_name  = "${RG}"
storage_account_name = "${SA}"
container_name       = "${CONTAINER}"
key                  = "erp/${env}/terraform.tfstate"
EOF
  green "Wrote ${dir}/backend.hcl"
done

echo
green "=============================================================="
green "Bootstrap complete."
green "=============================================================="
cat <<EOF

Next steps:

  cd infra/terraform/envs/dev
  cp terraform.tfvars.example terraform.tfvars
  \$EDITOR terraform.tfvars            # set owner_email and my_public_ip

  export ARM_USE_AZUREAD=true          # use Entra ID for the blob backend
  export TF_VAR_postgres_admin_password="\$(openssl rand -base64 24)"

  terraform init -backend-config=backend.hcl
  terraform plan -out=tfplan
  terraform apply tfplan

Things to remember:
  * ARM_USE_AZUREAD=true is REQUIRED because shared-key access is disabled.
    Without it you get "AuthorizationPermissionMismatch".
  * State is versioned with 30-day soft delete, so a corrupted apply is
    recoverable:  az storage blob list --include v ...
  * Never commit backend.hcl or terraform.tfvars - both are gitignored.
EOF
